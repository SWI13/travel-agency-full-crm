#!/usr/bin/env node
/**
 * One-time setup of the LOCAL Appwrite started with Docker (infra/appwrite).
 *
 * Creates the console account, an organisation, a project and a server API key,
 * then writes the connection settings to infra/appwrite/app.env (git-ignored).
 * Nothing is printed except what was created; the generated console password is
 * stored in infra/appwrite/console-login.txt.
 *
 *   node scripts/local-appwrite-bootstrap.mjs
 *
 * For Appwrite Cloud you do not need this script: create the project and key in
 * the Cloud console and put them in .env (see docs/DATABASE.md).
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "infra", "appwrite");
const ENDPOINT = (process.env.LOCAL_APPWRITE_ENDPOINT ?? "http://localhost:8080/v1").replace(/\/+$/, "");
const loginFile = path.join(dir, "console-login.txt");
const appEnvFile = path.join(dir, "app.env");

const SCOPES = [
  "databases.read", "databases.write", "tables.read", "tables.write", "columns.read", "columns.write",
  "indexes.read", "indexes.write", "rows.read", "rows.write", "users.read", "users.write", "sessions.read", "sessions.write",
];

let cookie = "";
async function call(method, route, body) {
  const response = await fetch(`${ENDPOINT}${route}`, {
    method,
    headers: {
      "Content-Type": "application/json",
      "X-Appwrite-Project": "console",
      "X-Appwrite-Response-Format": "1.8.0",
      ...(cookie ? { Cookie: cookie } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const setCookie = response.headers.getSetCookie?.() ?? [];
  const session = setCookie.map((c) => c.split(";")[0]).filter((c) => c.startsWith("a_session_console"));
  if (session.length) cookie = session.join("; ");
  const data = await response.json().catch(() => ({}));
  return { ok: response.ok, status: response.status, data };
}
const must = (label, result) => {
  if (!result.ok) throw new Error(`${label} failed (${result.status}): ${result.data?.message ?? JSON.stringify(result.data).slice(0, 200)}`);
  return result.data;
};

// Wait until Appwrite answers.
for (let attempt = 0; ; attempt++) {
  try {
    if ((await fetch(`${ENDPOINT}/health/version`)).ok) break;
  } catch {
    /* still starting */
  }
  if (attempt > 180) throw new Error(`Appwrite is not answering at ${ENDPOINT}. Is the Docker stack running?`);
  await new Promise((resolve) => setTimeout(resolve, 2000));
}

// Console account: reuse the saved login, otherwise create it.
let email = "owner@crm-local.test";
let password;
if (existsSync(loginFile)) {
  const saved = Object.fromEntries(readFileSync(loginFile, "utf8").split("\n").filter((l) => l.includes("=")).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).trim()]));
  email = saved.email ?? email;
  password = saved.password;
}
if (!password) {
  password = randomBytes(15).toString("base64url");
  must("Create console account", await call("POST", "/account", { userId: "unique()", email, password, name: "Local owner" }));
  writeFileSync(loginFile, `# Local Appwrite console (http://localhost:8080/console) — development only\nemail=${email}\npassword=${password}\n`, { mode: 0o600 });
  console.log("Console account created (login saved in infra/appwrite/console-login.txt).");
}
must("Console sign-in", await call("POST", "/account/sessions/email", { email, password }));

// Organisation: reuse the first one, otherwise create it.
const teams = must("List organisations", await call("GET", "/teams"));
let teamId = teams.teams?.[0]?.$id;
if (!teamId) {
  teamId = must("Create organisation", await call("POST", "/teams", { teamId: "unique()", name: "Agency" })).$id;
  console.log("Organisation created.");
}

// Project.
const projectId = "umrah-crm-local";
let project = await call("GET", `/projects/${projectId}`);
if (!project.ok) {
  project = { data: must("Create project", await call("POST", "/projects", { projectId, name: "Umrah CRM (local)", teamId, region: "default" })) };
  console.log(`Project "${projectId}" created.`);
}

// Server API key (a fresh one each run; old keys can be removed in the console).
const key = must("Create API key", await call("POST", `/projects/${projectId}/keys`, { name: `crm-server-${Date.now()}`, scopes: SCOPES, expire: null }));

writeFileSync(
  appEnvFile,
  `# Generated by scripts/local-appwrite-bootstrap.mjs — local development only, git-ignored.\nAPPWRITE_ENDPOINT=${ENDPOINT}\nAPPWRITE_PROJECT_ID=${projectId}\nAPPWRITE_API_KEY=${key.secret}\nAPPWRITE_DATABASE_ID=umrah_crm\n`,
  { mode: 0o600 },
);
console.log(`API key created with ${SCOPES.length} scopes. Connection settings written to infra/appwrite/app.env`);
